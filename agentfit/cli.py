from __future__ import annotations
import argparse,json,sys
from dataclasses import asdict
from agentfit.recommend import build_report
from agentfit.render import print_report
from agentfit.installer import install_command

def positive_int(v):
 try:n=int(v)
 except ValueError as e:raise argparse.ArgumentTypeError("must be an integer") from e
 if n<1:raise argparse.ArgumentTypeError("must be at least 1")
 return n
def build_parser():
 p=argparse.ArgumentParser(prog="agentfit",description="Find the smallest trustworthy tool stack that fits a task.")
 p.add_argument("task");p.add_argument("--limit",type=positive_int,default=8,help="maximum recommended stack size")
 p.add_argument("--no-npm",action="store_true");p.add_argument("--json",action="store_true");p.add_argument("--no-color",action="store_true");p.add_argument("-y","--yes",action="store_true",help="write a reviewable install script")
 return p
def main(argv=None):
 a=build_parser().parse_args(argv);r=build_report(a.task,use_npm=not a.no_npm,max_stack=a.limit)
 if a.json:print(json.dumps(asdict(r),indent=2));return 0
 print_report(r,not a.no_color);chosen=[x for x in r.recommendations if x.recommended]
 if not chosen:return 0
 ans="y" if a.yes else input("\nWrite a reviewable install script for selected tools? [Y/n] ").strip().lower()
 if ans in ("","y","yes"):
  lines=["#!/usr/bin/env bash","set -euo pipefail","","# Generated by AgentFit. REVIEW BEFORE RUNNING."]
  for x in chosen:lines += ["",f"# {x.candidate.name} — {x.reason}",install_command(x.candidate)]
  open("agentfit_install.sh","w",encoding="utf-8").write("\n".join(lines)+"\n");print("Wrote agentfit_install.sh — review it before execution.")
 return 0
if __name__=="__main__":sys.exit(main())
